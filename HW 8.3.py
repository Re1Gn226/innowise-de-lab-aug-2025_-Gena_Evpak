fruits = ["apple", "banana"]
fruits.append("orange") #добавляем апельсин
print(fruits)

fruits.insert(1, "grape") #добавляем виноград на индекс 1
print(fruits)

fruits.remove("banana") #удаляем банан
print(fruits)

fruits.sort() #сортируем список
print(fruits)

fruits.reverse() #переворачиваем список
print(fruits)
