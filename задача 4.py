scores = [75, 88, -10, 95, 100, -25, 89]
total_score = 0
for score in scores:
    # Проверка на отрицательный балл
    if score < 0:
        continue
    # Проверка на ноль
    if score == 0:
        print("Обработка прервана.")
        break  # выходим из цикла полностью
    # Если дошли сюда, значит балл положительный и не ноль - добавляем к сумме
    total_score += score
    print(f"Добавлен балл: {score}")
else:
    # Этот блок выполнится только если цикл не был прерван break
    print("Все данные успешно обработаны.")
print(f"Итоговая сумма баллов: {total_score}")