secret_number = 7
print("Угадайте число от 1 до 10")
user_input_number = int(input()) #Получаем первое число от пользователя и вводим переменную
while user_input_number != secret_number: #Цикл while выполняется до тех пор, пока число пользователя не совпадет с загаданным
    print("Неверно. Попробуйте еще раз.")
    user_input_number = int(input()) #Получаем следующее число от пользователя для новой попытки
print("Поздравляю! Вы угадали число")